#!/usr/bin/env python3
"""Generate the issue-9 dual-purpose LUT; never fit on validation captures.

Without captures, use an exhaustive uniform Q4/I4 geometry prior, NOT a
claim of measured RF quality. With --train/--validate, use whole independent
v3 raw snapshots. LUT words: low six bits DAC; bits 8..11 phase4(raw).
Address: prev | middle_signs << 4 | curr << 6 (Q sign then I sign).
"""
from pathlib import Path
import argparse
import hashlib
import json
import numpy as np
from golden_demod import exact_phase, wrap_r, scale, load, demod_production

ROOT = Path(__file__).resolve().parents[1]
PHI = exact_phase(np.arange(256, dtype=np.uint8))
P4 = np.rint(PHI * 16 / (2 * np.pi)).astype(np.uint16) & 15
QUAD = ((np.arange(256) >> 3) & 1) | ((np.arange(256) >> 6) & 2)


def observations(p, m, c):
    endpoint = wrap_r(PHI[c] - PHI[p])
    adjacent = wrap_r(PHI[m] - PHI[p]) + wrap_r(PHI[c] - PHI[m])
    branch = np.rint((adjacent - endpoint) / (2 * np.pi)).astype(int)
    target = scale(np.rint(wrap_r(adjacent) * 256 / (2 * np.pi)).astype(int))
    fallback = scale(np.rint(endpoint * 256 / (2 * np.pi)).astype(int))
    address = P4[p] | (QUAD[m] << 4) | (P4[c] << 6)
    return address, target, fallback, branch


def accumulate(groups):
    count = np.zeros(1024)
    sums = np.zeros(1024)
    endpoints = np.zeros(1024)
    branches = np.zeros((1024, 3))
    for p, m, c in groups:
        a, t, e, b = observations(p, m, c)
        count += np.bincount(a, minlength=1024)
        sums += np.bincount(a, weights=t, minlength=1024)
        endpoints += np.bincount(a, weights=e, minlength=1024)
        branches += np.bincount(a * 3 + b + 1, minlength=3072).reshape(1024, 3)
    return count, sums, endpoints, branches


def prior_groups():
    m, c = np.indices((256, 256)).reshape(2, -1)
    for p in range(256):
        yield np.full(len(m), p), m, c


def capture_groups(paths):
    for path in paths:
        hdr, raw = load(path)
        if hdr['iq_rate_hz'] != 40_000_000 or hdr['cvbs_rate_hz'] not in (0, 20_000_000):
            raise ValueError(f'{path}: requires raw 40 -> 20 MS/s snapshot')
        if len(raw) < 4:
            raise ValueError(f'{path}: too short')
        n = (len(raw) - 2) // 2
        yield raw[1:1+2*n:2], raw[2:2+2*n:2], raw[3:3+2*n:2]


def select(stats, fallback=None, min_count=16, confidence=.85):
    count, sums, endpoints, branches = stats
    denom = np.maximum(count, 1)
    conservative = np.rint(endpoints / denom).astype(int)
    if fallback is not None:
        conservative[count < min_count] = fallback[count < min_count]
    trusted = (count >= min_count) & (branches.max(axis=1) / denom >= confidence)
    dac = np.where(trusted, np.rint(sums / denom), conservative).astype(np.uint16)
    return dac, trusted


def words(dac):
    result = dac.copy()
    result[:256] |= P4 << 8
    return result


def write_outputs(dac):
    lut = words(dac)
    asm = ROOT / 'main/c5vrx2_wbfm_q4_trajectory_2to1.bsasm'
    text = asm.read_text()
    lines = text.splitlines()
    lines = [('lut ' + ' '.join(map(str, lut))) if line.startswith('lut ') else line for line in lines]
    asm.write_text('\n'.join(lines) + '\n')
    h = ['/* Generated by tools/train_trajectory_lut.py; default gain=2, pedestal=20. */',
         '#pragma once', '#include <stdint.h>',
         'static const uint16_t c5vrx2_trajectory_lut[1024] = {']
    h += ['    ' + ', '.join(map(str, lut[i:i+16])) + ',' for i in range(0, 1024, 16)]
    h += ['};', '']
    (ROOT / 'main/trajectory_lut.h').write_text('\n'.join(h))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--train', type=Path, nargs='+', default=[])
    ap.add_argument('--validate', type=Path, nargs='+', default=[])
    ap.add_argument('--min-count', type=int, default=2)
    ap.add_argument('--write', action='store_true')
    args = ap.parse_args()
    hashes = lambda paths: {hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
    if hashes(args.train) & hashes(args.validate):
        ap.error('training and validation captures overlap (content hash)')
    if args.train and not args.validate:
        ap.error('capture training requires independent --validate captures')
    stats = accumulate(prior_groups())
    dac, trusted = select(stats)
    if args.train:
        dac, trusted = select(accumulate(capture_groups(args.train)), dac, min_count=args.min_count)
    report = {'source': 'captures' if args.train else 'exhaustive uniform geometry prior',
              'trusted_addresses': int(trusted.sum()), 'dac_levels': int(len(np.unique(dac))),
              'train_sha256': sorted(hashes(args.train)), 'validation': []}
    for path, (p, m, c) in zip(args.validate, capture_groups(args.validate)):
        a, t, _, _ = observations(p, m, c)
        _, raw = load(path)
        baseline = demod_production(raw).astype(int)
        report['validation'].append({'file': path.name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
            **{name: {'mae': float(np.abs(v.astype(int)-t).mean()),
                      'hard_ge16': float((np.abs(v.astype(int)-t) >= 16).mean()),
                      'levels': int(len(np.unique(v)))}
               for name, v in [('trajectory', dac[a]), ('phase5', baseline)]}})
    if args.write:
        write_outputs(dac)
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    main()
