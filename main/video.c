    menu_draw_string(0, 16, buf);

    snprintf(buf, sizeof(buf), "%c [1] BAND:   %s",
             (s_menu_cursor == 0) ? '>' : ' ', rf_get_band_name(rf_get_current_band()));
    menu_draw_string(1, 16, buf);

